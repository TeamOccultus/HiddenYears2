import * as esbuild from "esbuild";
import * as rolldown from "rolldown";
import * as fs from "fs-extra";
import archiver from "archiver";
import path from "path";
import JSON5 from "json5";
import {
  createWriteStream,
  readdirSync,
  writeFileSync,
  readFileSync,
} from "fs";

// Why we need a callback?
// because rolldown currently does not have anything like `buildSync`
// We need to ensure mcpacks is only packed after scripts are built
export function buildScript(callback) {
  // Build script
  if (process.argv.includes("rolldown")) {
    console.warn("TIP: 已启用试验性脚本构建: rolldown");
    rolldown
      .build({
        input: "src/index.ts",
        external: ["@minecraft/server", "@minecraft/server-ui"],
        treeshake: true,
        platform: "neutral",
        write: true,
        output: {
          file: "HiddenYears(BP)/scripts/index.js",
          exports: "none",
          minify: true,
        },
        keepNames: true,
      })
      .then((r) => {
        console.log("SUCCESS: 脚本编译完成");
        callback();
      });
  } else {
    esbuild.buildSync({
      entryPoints: ["src/index.ts"],
      bundle: true,
      outfile: "./HiddenYears(BP)/scripts/index.js",
      format: "esm",
      external: ["@minecraft/server", "@minecraft/server-ui"],
      minify: true,
      treeShaking: true,
      keepNames: true,
    });
    callback();
    console.log("SUCCESS: 脚本编译完成");
  }
}

export function buildMcpacks() {
  const OUTPUT_DIR = path.join(process.cwd(), "output");
  const DIRS = ["HiddenYears(BP)", "HiddenYears(RP)"];
  fs.ensureDirSync(path.join(OUTPUT_DIR, "mcpacks"));
  DIRS.forEach((dir) => {
    const archive = archiver("zip");
    archive.pipe(
      createWriteStream(path.join(OUTPUT_DIR, "mcpacks", `${dir}.mcpack`)),
    );
    archive.directory(path.join(process.cwd(), dir), false);
    archive.finalize();
    console.log(`INFO: ${dir} 打包成功`);
  });
  console.log("INFO: 所有.mcpack文件打包成功");
}

export function finalize() {
  const OUTPUT_DIR = path.join(process.cwd(), "output");
  const mcaddonArchive = archiver("zip");
  const mcpacks = readdirSync(path.join(OUTPUT_DIR, "mcpacks"));
  console.log(mcpacks);

  mcaddonArchive.pipe(
    createWriteStream(path.join(OUTPUT_DIR, "HiddenYears2.mcaddon.zip")),
  );

  mcpacks.forEach((file) => {
    const file_path = path.join(OUTPUT_DIR, "mcpacks", file);
    mcaddonArchive.file(file_path, {
      name: file,
    });
    console.log(`INFO: ${file} 已添加到输出文件`);
  });
  mcaddonArchive.finalize();
  console.log("SUCCESS: 附加包打包成功");
}

export function generateLangFile(input, output) {
  const data = readFileSync(input);
  const json = JSON5.parse(data);
  fs.ensureFileSync(output);
  let langdata =
    "## This file auto generated by javascript, do not edit it!\n\n";
  for (const key in json) {
    langdata += `${key}=${json[key]}\n`;
  }

  writeFileSync(output, langdata);
  const langName = path.parse(output).name;
  console.log(`INFO: 语言 ${langName} 编译完成`);
}

export function generateLangSet(path, ...languages) {
  let langSet = [];
  languages.forEach((lang) => {
    langSet.push(lang);
  });
  const str = JSON.stringify(langSet, null, 2);
  writeFileSync(path, str);
}

export function buildLang() {
  generateLangFile("lang/zh_CN.json", "HiddenYears(RP)/texts/zh_CN.lang");
  generateLangFile("lang/zh_TW.json", "HiddenYears(RP)/texts/zh_TW.lang");
  generateLangFile("lang/en_US.json", "HiddenYears(RP)/texts/en_US.lang");
  generateLangSet(
    "HiddenYears(RP)/texts/language.json",
    "zh_CN",
    "zh_TW",
    "en_US",
  );
  console.log("SUCCESS: 语言文件编译完成");
}
