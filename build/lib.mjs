import * as esbuild from "esbuild";
import * as rolldown from "rolldown";
import * as fs from "fs-extra";
import archiver from "archiver";
import path from "path";
import JSON5 from "json5";
import {
  createWriteStream,
  writeFileSync,
  readFileSync,
  readdirSync,
  cp,
  cpSync,
} from "fs";
import chalk from "chalk";

// Why we need a callback?
// because rolldown currently does not have anything like `buildSync`
// We need to ensure mcpacks is only packed after scripts are built
// 说的很不错，就是下回可以说中文吗，方便交流 awa
export function buildScript(callback) {
  // Build script
  if (process.argv.includes("rolldown")) {
    console.warn("TIP: 已启用试验性脚本构建: rolldown");
    rolldown
      .build({
        input: "src/index.ts",
        external: ["@minecraft/server", "@minecraft/server-ui"],
        treeshake: true,
        platform: "neutral",
        write: true,
        output: {
          file: "HiddenYears(BP)/scripts/index.js",
          exports: "none",
          minify: true,
        },
        keepNames: true,
      })
      .then((r) => {
        console.log(
          chalk.green.bold.inverse(" SUCCESS ") +
            " 脚本编译完成" +
            " (Using Rolldown v" +
            rolldown.VERSION +
            ")"
        );
        callback?.();
      });
  } else {
    esbuild.buildSync({
      entryPoints: ["src/index.ts"],
      bundle: true,
      outfile: "./HiddenYears(BP)/scripts/index.js",
      format: "esm",
      external: ["@minecraft/server", "@minecraft/server-ui"],
      minify: true,
      treeShaking: true,
      keepNames: true,
    });
    callback?.();
    console.log(
      chalk.green.bold.inverse(" SUCCESS ") +
        " 脚本编译完成" +
        " (Using Esbuild v" +
        esbuild.version +
        ")"
    );
  }
}

export function buildMcpacks() {
  const OUTPUT_DIR = path.join(process.cwd(), "output");
  const DIRS = ["HiddenYears(BP)", "HiddenYears(RP)"];
  fs.ensureDirSync(path.join(OUTPUT_DIR, "mcpacks"));
  DIRS.forEach((dir) => {
    const archive = archiver("zip");
    archive.pipe(
      createWriteStream(path.join(OUTPUT_DIR, "mcpacks", `${dir}.mcpack`))
    );
    archive.directory(path.join(process.cwd(), dir), false);
    archive.finalize();
    console.log(chalk.bold(" INFO ") + `${dir} 打包成功`);
  });
  console.log(chalk.bold(" INFO ") + "所有 .mcpack 文件打包成功");
}

export function finalize() {
  const OUTPUT_DIR = path.join(process.cwd(), "output");
  const mcaddonArchive = archiver("zip");
  const mcpacks = readdirSync(path.join(OUTPUT_DIR, "mcpacks"));
  console.log(mcpacks);

  mcaddonArchive.pipe(
    createWriteStream(path.join(OUTPUT_DIR, "HiddenYears2.mcaddon.zip"))
  );

  mcpacks.forEach((file) => {
    const file_path = path.join(OUTPUT_DIR, "mcpacks", file);
    mcaddonArchive.file(file_path, {
      name: file,
    });
    console.log(chalk.bold(" INFO ") + `${file} 已添加到输出文件`);
  });
  mcaddonArchive.finalize();
  console.log(chalk.green.bold.inverse(" SUCCESS ") + " 附加包打包成功");
}

export function generateLangFile(input, output) {
  const data = readFileSync(input);
  const json = JSON5.parse(data);
  fs.ensureFileSync(output);
  let langdata =
    "## This file auto generated by javascript, do not edit it!\n\n";
  for (const key in json) {
    langdata += `${key}=${json[key]}\n`;
  }

  writeFileSync(output, langdata);
  const langName = path.parse(output).name;
  console.log(chalk.bold(" INFO ") + `语言 ${langName} 编译完成`);
}

export function generateLangSet(path, ...languages) {
  let langSet = [];
  languages.forEach((lang) => {
    langSet.push(lang);
  });
  const str = JSON.stringify(langSet, null, 2);
  writeFileSync(path, str);
}

export function buildLang() {
  generateLangFile("lang/zh_CN.json", "HiddenYears(RP)/texts/zh_CN.lang");
  generateLangFile("lang/zh_TW.json", "HiddenYears(RP)/texts/zh_TW.lang");
  generateLangFile("lang/en_US.json", "HiddenYears(RP)/texts/en_US.lang");
  generateLangSet(
    "HiddenYears(RP)/texts/languages.json",
    "zh_CN",
    "zh_TW",
    "en_US"
  );
  console.log(chalk.green.bold.inverse(" SUCCESS ") + " 语言文件编译完成");
}

export function genResourceIndex() {
  const itemTexure = readdirSync("assets/items");
  const blockTexture = readdirSync("assets/blocks");
  const itemIndex = {
    resource_pack_name: "隐藏之年²",
    texture_name: "atlas.items",
    texture_data: {},
  };
  const blockIndex = {
    num_mip_levels: 4,
    padding: 8,
    resource_pack_name: "隐藏之年²",
    texture_name: "atlas.terrain",
    texture_data: {},
  };
  itemTexure.forEach((file) => {
    itemIndex.texture_data["hy:"+ file.replaceAll(".png", "")] = {
      "textures": `textures/items/${file.replaceAll(".png", "")}`
    }
  })
  blockTexture.forEach((file) => {
    blockIndex.texture_data["hy:"+ file.replaceAll(".png", "")] = {
      "textures": `textures/blocks/${file.replaceAll(".png", "")}`
    }
  })
  writeFileSync("HiddenYears(RP)/textures/item_texture.json", JSON.stringify(itemIndex, null, 2));
  writeFileSync("HiddenYears(RP)/textures/terrain_texture.json", JSON.stringify(blockIndex, null, 2));
  console.log(chalk.green.bold.inverse(" SUCCESS ") + " 资源索引生成完成");
}

export function copyAssets() {
  fs.ensureDirSync("HiddenYears(RP)/textures/items");
  fs.ensureDirSync("HiddenYears(RP)/textures/blocks");
  cpSync("assets/items", "HiddenYears(RP)/textures/items", {recursive: true});
  cpSync("assets/blocks", "HiddenYears(RP)/textures/blocks", {recursive: true});
  console.log(chalk.green.bold.inverse(" SUCCESS ") + " 资源文件拷贝完成");
}